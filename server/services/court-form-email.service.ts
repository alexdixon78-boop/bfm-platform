import { formatCaseEmailSubject } from "../utils/case-communication-format";
import { emailTemplateService } from "./email-template.service";

const SENDGRID_API_KEY = process.env.SENDGRID_API_KEY;
const FROM_EMAIL = process.env.SENDGRID_FROM_EMAIL || "info@brighterfuturemediation.co.uk";
const FROM_NAME = "Brighter Future Mediation";

type EmailResult = { sent: boolean; error?: string | null };

function humanizeSendGridError(status: number, statusText: string, body: string): string {
  const trimmed = body.trim();
  if (!trimmed) return `SendGrid returned ${status} ${statusText}`;
  try {
    const parsed = JSON.parse(trimmed) as { errors?: Array<{ message?: string; field?: string }>; message?: string };
    if (parsed.errors?.length) {
      return `SendGrid returned ${status} ${statusText}: ${parsed.errors.map((e) => `${e.field ? `${e.field}: ` : ""}${e.message || "Unknown error"}`).join("; ")}`;
    }
    if (parsed.message) return `SendGrid returned ${status} ${statusText}: ${parsed.message}`;
  } catch {
    return `SendGrid returned ${status} ${statusText}: ${trimmed}`;
  }
  return `SendGrid returned ${status} ${statusText}: ${trimmed}`;
}

export async function sendCourtFormPdfEmail(input: {
  to: string;
  clientName: string;
  caseRef: string;
  formName: string;
  fileName: string;
  pdfBuffer: Buffer;
}): Promise<EmailResult> {
  if (!SENDGRID_API_KEY) return { sent: false, error: "SENDGRID_API_KEY not configured" };
  const html = `
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
      <h2 style="color: #5a7d58;">${input.formName} generated</h2>
      <p>Hello ${input.clientName},</p>
      <p>Please find attached your generated ${input.formName} for case ${input.caseRef}.</p>
      <p>This document has been generated by Brighter Future Mediation from the information currently held on your case record.</p>
      <hr style="border: none; border-top: 1px solid #eee; margin: 30px 0;">
      <p style="color: #999; font-size: 12px;">Brighter Future Mediation</p>
    </div>
  `;
  let rendered: { subject: string; bodyHtml: string };
  try {
    rendered = await emailTemplateService.systemOverride("SYSTEM_COURT_FORM_PDF", { subject: formatCaseEmailSubject(input.formName, input.caseRef), bodyHtml: html }, { original_subject: formatCaseEmailSubject(input.formName, input.caseRef), form_name: input.formName, client_name: input.clientName, case_ref: input.caseRef });
  } catch (error) {
    console.error("[Email] Court form template unavailable; using current wording", error);
    rendered = { subject: formatCaseEmailSubject(input.formName, input.caseRef), bodyHtml: html };
  }
  const payload = {
    personalizations: [{ to: [{ email: input.to }] }],
    from: { email: FROM_EMAIL, name: FROM_NAME },
    subject: rendered.subject,
    content: [{ type: "text/html", value: rendered.bodyHtml }],
    attachments: [{
      content: input.pdfBuffer.toString("base64"),
      filename: input.fileName,
      type: "application/pdf",
      disposition: "attachment",
    }],
  };

  try {
    const res = await fetch("https://api.sendgrid.com/v3/mail/send", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${SENDGRID_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });
    if (!res.ok) return { sent: false, error: humanizeSendGridError(res.status, res.statusText, await res.text()) };
    return { sent: true, error: null };
  } catch (err) {
    return { sent: false, error: err instanceof Error ? err.message : String(err) };
  }
}
