import { eq } from "drizzle-orm";
import { db } from "../db";
import { emailTemplateLinks, emailTemplates, type EmailTemplate } from "@shared/schema";
import { renderTemplate, validatePublication } from "@shared/email-template-core";
import { renderEmailHtml, sanitizeEmailHtml } from "./email-template-html";
import { docxLinkCatalog, docxTemplateCatalog } from "./email-template-catalog";
import { systemEmailCatalog } from "./system-email-catalog";
import { JSDOM } from "jsdom";

export type TemplateInput = Pick<EmailTemplate, "code" | "name" | "subject" | "bodyHtml"> & Partial<Pick<EmailTemplate, "guidance" | "variables" | "requiredVariables" | "kind" | "status" | "isArchived">>;

class EmailTemplateService {
  private seedPromise: Promise<void> | null = null;

  async ensureCatalog(): Promise<void> {
    if (!this.seedPromise) this.seedPromise = this.seedCatalog();
    try { await this.seedPromise; } catch (error) { this.seedPromise = null; throw error; }
  }

  private async seedCatalog(): Promise<void> {
    await db.insert(emailTemplates).values(docxTemplateCatalog.map(item => ({
      ...item,
      bodyHtml: sanitizeEmailHtml(item.bodyHtml),
      requiredVariables: [] as string[],
    }))).onConflictDoNothing();
    await db.insert(emailTemplates).values(systemEmailCatalog.map(item => ({ ...item, bodyHtml: sanitizeEmailHtml(item.bodyHtml) }))).onConflictDoNothing();
    await db.insert(emailTemplates).values({
      code: "SYSTEM_COURT_FORM_PDF", name: "Court form PDF delivery", kind: "system", status: "published",
      subject: "{{original_subject}}", bodyHtml: "<h2>{{form_name}} generated</h2><p>Hello {{client_name}},</p><p>Please find attached your generated {{form_name}} for case {{case_ref}}.</p><p>This document has been generated by Brighter Future Mediation from the information currently held on your case record.</p>",
      guidance: "Automatic email with the approved PDF attachment. The attachment is always supplied by the court form workflow.",
      variables: [{ key: "form_name", label: "Form name" }, { key: "client_name", label: "Client name" }, { key: "case_ref", label: "Case reference" }],
      requiredVariables: ["form_name", "client_name", "case_ref"],
    }).onConflictDoNothing();
    await db.insert(emailTemplateLinks).values(docxLinkCatalog.filter(item => /^https:\/\//.test(item.url))).onConflictDoNothing();
  }

  async list(includeArchived = false): Promise<EmailTemplate[]> {
    await this.ensureCatalog();
    const rows = await db.select().from(emailTemplates).orderBy(emailTemplates.code);
    return includeArchived ? rows : rows.filter(row => !row.isArchived);
  }

  async get(id: string): Promise<EmailTemplate | undefined> {
    await this.ensureCatalog();
    return (await db.select().from(emailTemplates).where(eq(emailTemplates.id, id)).limit(1))[0];
  }

  async getByCode(code: string): Promise<EmailTemplate | undefined> {
    await this.ensureCatalog();
    return (await db.select().from(emailTemplates).where(eq(emailTemplates.code, code)).limit(1))[0];
  }

  async create(input: TemplateInput, actorId: string): Promise<EmailTemplate> {
    const status = input.status === "published" ? "published" : "draft";
    const bodyHtml = sanitizeEmailHtml(input.bodyHtml);
    if (status === "published") {
      const error = validatePublication({ ...input, bodyHtml, requiredVariables: input.requiredVariables || [] });
      if (error) throw new Error(error);
    }
    const [created] = await db.insert(emailTemplates).values({ ...input, bodyHtml, status, kind: input.kind || "manual", variables: input.variables || [], requiredVariables: input.requiredVariables || [], createdBy: actorId, updatedBy: actorId }).returning();
    return created;
  }

  async update(id: string, input: Partial<TemplateInput>, actor: { id: string; role: string }): Promise<EmailTemplate | undefined> {
    const existing = await this.get(id);
    if (!existing) return undefined;
    if (input.code !== undefined && input.code !== existing.code) throw new Error("Template codes cannot be changed");
    if (input.kind !== undefined && input.kind !== existing.kind) throw new Error("Template type cannot be changed");
    if (existing.kind === "system" && (input.requiredVariables !== undefined || (input.status !== undefined && input.status !== "published"))) throw new Error("System template safeguards cannot be changed");
    if (existing.kind === "system" && input.isArchived) throw new Error("Automatic system templates cannot be archived");
    if (existing.kind !== "system" && actor.role !== "superadmin" && (existing.status === "published" || input.status === "published")) throw new Error("Only a Super Admin can change published review templates");
    if (existing.code === "X1" && existing.status === "published" && actor.role !== "superadmin") throw new Error("Only a Super Admin can change X1");
    const bodyHtml = input.bodyHtml === undefined ? existing.bodyHtml : sanitizeEmailHtml(input.bodyHtml);
    const next = { ...existing, ...input, bodyHtml, requiredVariables: existing.kind === "system" ? existing.requiredVariables : input.requiredVariables || existing.requiredVariables };
    const protectedWording: Record<string, string> = { SYSTEM_PASSWORD_RESET: "expire in 1 hour", SYSTEM_PORTAL_INVITE: "expire in 7 days", SYSTEM_MEDIATOR_INVITE: "expire in 7 days", SYSTEM_CONTRACTOR_INVITE: "expire in 7 days", SYSTEM_WHATS_APP_CASE_OTP: "expires in 10 minutes", PORTAL_INVITE: "expire in 7 days" };
    if (protectedWording[existing.code] && !bodyHtml.toLowerCase().includes(protectedWording[existing.code])) throw new Error(`Required expiry wording must remain: ${protectedWording[existing.code]}`);
    if (existing.kind === "system" && existing.requiredVariables.some(key => !bodyHtml.includes(`{{${key}}}`))) throw new Error("Required security variables must remain in the message body");
    if (next.status === "published") {
      const error = validatePublication(next);
      if (error) throw new Error(error);
    }
    const [updated] = await db.update(emailTemplates).set({ ...input, bodyHtml, contentOverride: existing.contentOverride || input.subject !== undefined || input.bodyHtml !== undefined, updatedBy: actor.id, updatedAt: new Date() }).where(eq(emailTemplates.id, id)).returning();
    return updated;
  }

  async links(): Promise<typeof emailTemplateLinks.$inferSelect[]> {
    await this.ensureCatalog();
    return db.select().from(emailTemplateLinks).orderBy(emailTemplateLinks.key);
  }

  async updateLink(key: string, url: string, actorId: string) {
    if (!/^https:\/\//.test(url)) throw new Error("Use a secure HTTPS link");
    const [updated] = await db.update(emailTemplateLinks).set({ url, updatedBy: actorId, updatedAt: new Date() }).where(eq(emailTemplateLinks.key, key)).returning();
    return updated;
  }

  async render(subject: string, bodyHtml: string, values: Record<string, string | null | undefined>, requiredVariables: string[] = [], preserveHtmlFragments = false, options: { allowBlankOptionalVariables?: boolean } = {}) {
    const links = await this.links();
    const merged = { ...values, ...Object.fromEntries(links.map(link => [link.key, link.url])) };
    const renderOptions = { allowBlankOptionalVariables: options.allowBlankOptionalVariables, requiredVariables };
    const renderedSubject = renderTemplate(subject, merged, false, renderOptions);
    const renderedBody = preserveHtmlFragments ? renderEmailHtml(bodyHtml, merged, renderOptions) : renderTemplate(sanitizeEmailHtml(bodyHtml), merged, true, renderOptions);
    const missing = Array.from(new Set([...renderedSubject.missing, ...renderedBody.missing, ...requiredVariables.filter(key => !merged[key])]));
    return { subject: renderedSubject.output, bodyHtml: sanitizeEmailHtml(renderedBody.output), missing };
  }

  async availableForCompose(): Promise<EmailTemplate[]> {
    return (await this.list()).filter(item => item.status === "published" && (item.kind === "manual" || item.code === "PORTAL_INVITE" || item.code === "SYSTEM_MIAM_INVITE"));
  }

  async calendarDescription(code: string, values: Record<string, string | null | undefined>): Promise<string | null> {
    try {
      const template = await this.getByCode(code);
      if (!template || template.kind !== "calendar" || template.status !== "published" || template.isArchived) return null;
      const rendered = await this.render("", template.bodyHtml, values);
      if (rendered.missing.length) return null;
      const document = new JSDOM(rendered.bodyHtml).window.document;
      for (const anchor of Array.from(document.body.querySelectorAll("a[href]"))) {
        anchor.replaceWith(`${anchor.textContent?.trim() || "Link"}: ${anchor.getAttribute("href")}`);
      }
      return Array.from(document.body.querySelectorAll("p, li"))
        .map(node => node.textContent?.trim() || "")
        .filter(Boolean)
        .join("\n") || null;
    } catch (error) {
      console.error(`[Email templates] Calendar description ${code} could not render`, error);
      return null;
    }
  }

  async systemOverride(code: string, fallback: { subject: string; bodyHtml: string }, values: Record<string, string | null | undefined>) {
    const template = await this.getByCode(code);
    if (!template || template.isArchived) throw new Error(`System template ${code} is unavailable`);
    if (!template.contentOverride) return { subject: fallback.subject, bodyHtml: fallback.bodyHtml };
    const rendered = await this.render(template.subject, template.bodyHtml, values, template.requiredVariables || [], true);
    if (rendered.missing.length) throw new Error(`Missing template values: ${rendered.missing.join(", ")}`);
    return rendered;
  }
}

export const emailTemplateService = new EmailTemplateService();
