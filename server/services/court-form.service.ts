import { storage } from "../storage";
import type { Case, Party } from "@shared/schema";

export type CourtFormType = "C100" | "FormA" | "FM1";

interface CourtFormData {
  caseRef: string;
  caseId: string;
  formType: CourtFormType;
  partyA?: Party;
  partyB?: Party;
  generatedAt: Date;
}

function escapeText(t: string | null | undefined): string {
  return (t || "—").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function generatePlaceholderHtml(data: CourtFormData): string {
  const formTitles: Record<CourtFormType, string> = {
    C100: "C100 — Application under the Children Act 1989",
    FormA: "Form A — Notice of Application for a Financial Order",
    FM1: "FM1 — Family Mediation Information and Assessment Form",
  };

  const title = formTitles[data.formType];
  const partyAName = data.partyA ? `${escapeText(data.partyA.firstName)} ${escapeText(data.partyA.lastName)}` : "—";
  const partyBName = data.partyB ? `${escapeText(data.partyB.firstName)} ${escapeText(data.partyB.lastName)}` : "—";
  const partyADob = data.partyA?.dateOfBirth ? new Date(data.partyA.dateOfBirth).toLocaleDateString("en-GB") : "—";
  const partyBDob = data.partyB?.dateOfBirth ? new Date(data.partyB.dateOfBirth).toLocaleDateString("en-GB") : "—";
  const partyAAddress = data.partyA ? [data.partyA.addressLine1, data.partyA.addressLine2, data.partyA.city, data.partyA.postcode].filter(Boolean).join(", ") || "—" : "—";
  const partyBAddress = data.partyB ? [data.partyB.addressLine1, data.partyB.addressLine2, data.partyB.city, data.partyB.postcode].filter(Boolean).join(", ") || "—" : "—";

  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>${escapeText(title)}</title>
<style>
  body { font-family: Arial, sans-serif; margin: 40px; color: #333; }
  h1 { font-size: 18px; border-bottom: 2px solid #333; padding-bottom: 8px; }
  h2 { font-size: 14px; margin-top: 24px; color: #555; text-transform: uppercase; letter-spacing: 1px; }
  .field { margin: 8px 0; }
  .label { font-weight: bold; font-size: 12px; color: #666; text-transform: uppercase; }
  .value { font-size: 14px; margin-top: 2px; }
  .placeholder-notice { background: #fff3cd; border: 1px solid #ffc107; padding: 12px; margin: 20px 0; border-radius: 4px; font-size: 12px; }
  .footer { margin-top: 40px; font-size: 11px; color: #999; border-top: 1px solid #ddd; padding-top: 8px; }
  table { width: 100%; border-collapse: collapse; margin-top: 12px; }
  td { padding: 6px 8px; border: 1px solid #ddd; font-size: 13px; vertical-align: top; }
  td.label-cell { background: #f5f5f5; width: 30%; font-weight: bold; font-size: 12px; }
</style>
</head>
<body>
  <h1>${escapeText(title)}</h1>
  <div class="placeholder-notice">
    <strong>PLACEHOLDER DOCUMENT</strong> — This is a draft court form generated from case data.
    The final version must be reviewed, completed, and signed before submission to the court.
    Template will be replaced with the official form layout.
  </div>

  <h2>Case Details</h2>
  <table>
    <tr><td class="label-cell">Case Reference</td><td>${escapeText(data.caseRef)}</td></tr>
    <tr><td class="label-cell">Form Type</td><td>${escapeText(data.formType)}</td></tr>
    <tr><td class="label-cell">Generated</td><td>${data.generatedAt.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })} at ${data.generatedAt.toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit" })}</td></tr>
  </table>

  <h2>Applicant (Client A)</h2>
  <table>
    <tr><td class="label-cell">Full Name</td><td>${escapeText(partyAName)}</td></tr>
    <tr><td class="label-cell">Date of Birth</td><td>${escapeText(partyADob)}</td></tr>
    <tr><td class="label-cell">Email</td><td>${escapeText(data.partyA?.email)}</td></tr>
    <tr><td class="label-cell">Phone</td><td>${escapeText(data.partyA?.phone ? `${data.partyA.phoneCode || "+44"} ${data.partyA.phone}` : null)}</td></tr>
    <tr><td class="label-cell">Address</td><td>${escapeText(partyAAddress)}</td></tr>
  </table>

  <h2>Respondent (Client B)</h2>
  <table>
    <tr><td class="label-cell">Full Name</td><td>${escapeText(partyBName)}</td></tr>
    <tr><td class="label-cell">Date of Birth</td><td>${escapeText(partyBDob)}</td></tr>
    <tr><td class="label-cell">Email</td><td>${escapeText(data.partyB?.email)}</td></tr>
    <tr><td class="label-cell">Phone</td><td>${escapeText(data.partyB?.phone ? `${data.partyB.phoneCode || "+44"} ${data.partyB.phone}` : null)}</td></tr>
    <tr><td class="label-cell">Address</td><td>${escapeText(partyBAddress)}</td></tr>
  </table>

  <div class="footer">
    Brighter Future Mediation Ltd &bull; FMC Accredited &bull; Generated by BFM Case Management System
  </div>
</body>
</html>`;
}

export class CourtFormService {
  async generateCourtForm(caseId: string, formType: CourtFormType): Promise<{ html: string; filename: string } | null> {
    const caseData = await storage.getCase(caseId);
    if (!caseData) return null;

    const parties = await storage.listPartiesByCase(caseId);
    const partyA = parties.find(p => p.role === "Client A");
    const partyB = parties.find(p => p.role === "Client B");

    const data: CourtFormData = {
      caseRef: caseData.caseRef,
      caseId: caseData.id,
      formType,
      partyA,
      partyB,
      generatedAt: new Date(),
    };

    const html = generatePlaceholderHtml(data);
    const filename = `${formType}_${caseData.caseRef.replace(/\//g, "-")}_${new Date().toISOString().slice(0, 10)}.html`;

    return { html, filename };
  }
}

export const courtFormService = new CourtFormService();
