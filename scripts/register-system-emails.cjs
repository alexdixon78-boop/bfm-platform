// Generate an editable catalog and explicit send-site registration from the existing email functions.
const fs = require("node:fs");
const ts = require("typescript");

const sourcePath = "server/services/email.service.ts";
const outputPath = "server/services/system-email-catalog.ts";
const source = fs.readFileSync(sourcePath, "utf8");
const file = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true);
const catalog = [];
const insertions = [];

function snake(value) { return value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^a-zA-Z0-9]+/g, "_").toLowerCase().replace(/^_|_$/g, ""); }
function findNodes(root, predicate) { const found = []; function walk(node) { if (predicate(node)) found.push(node); ts.forEachChild(node, walk); } walk(root); return found; }

for (const fn of file.statements.filter(ts.isFunctionDeclaration)) {
  if (!fn.name || !fn.body || !fn.name.text.startsWith("send")) continue;
  const calls = findNodes(fn.body, node => ts.isCallExpression(node) && node.expression.getText(file) === "sendEmail" && ts.isObjectLiteralExpression(node.arguments[0]));
  if (calls.length !== 1) continue;
  const call = calls[0];
  const object = call.arguments[0];
  const alreadyRegistered = object.properties.some(prop => prop.name?.getText(file) === "templateCode");
  const htmlProp = object.properties.find(prop => prop.name?.getText(file) === "html");
  let htmlNode = ts.isPropertyAssignment(htmlProp) ? htmlProp.initializer : undefined;
  if (!htmlNode || ts.isIdentifier(htmlNode)) {
    const declarations = findNodes(fn.body, node => ts.isVariableDeclaration(node) && node.name.getText(file) === "html");
    htmlNode = declarations[0]?.initializer;
  }
  if (!htmlNode || (!ts.isTemplateExpression(htmlNode) && !ts.isNoSubstitutionTemplateLiteral(htmlNode))) throw new Error(`Cannot extract ${fn.name.text}`);
  const expressions = new Map();
  function token(expression) {
    const code = expression.getText(file);
    const existing = expressions.get(code);
    if (existing) return `{{${existing}}}`;
    const preferred = ts.isIdentifier(expression) ? snake(code) : `value_${expressions.size + 1}`;
    let key = preferred;
    while ([...expressions.values()].includes(key)) key = `${preferred}_${expressions.size + 1}`;
    expressions.set(code, key);
    return `{{${key}}}`;
  }
  let bodyHtml = ts.isNoSubstitutionTemplateLiteral(htmlNode) ? htmlNode.text : htmlNode.head.text + htmlNode.templateSpans.map(span => token(span.expression) + span.literal.text).join("");
  const subjectProp = object.properties.find(prop => prop.name?.getText(file) === "subject");
  let subjectNode = ts.isPropertyAssignment(subjectProp) ? subjectProp.initializer : undefined;
  if (!subjectNode || ts.isIdentifier(subjectNode)) {
    const declarations = findNodes(fn.body, node => ts.isVariableDeclaration(node) && node.name.getText(file) === "subject");
    subjectNode = declarations[0]?.initializer;
  }
  const defaultSubject = subjectNode && (ts.isStringLiteral(subjectNode) || ts.isNoSubstitutionTemplateLiteral(subjectNode)) ? subjectNode.text : "{{original_subject}}";
  const code = `SYSTEM_${snake(fn.name.text.replace(/^send/, "").replace(/Email$/, "")).toUpperCase()}`;
  const requiredVariables = [...new Set([...expressions.values()].filter(key => /(?:^|_)(?:url|link|code|token)$/.test(key)))];
  catalog.push({ code, name: fn.name.text.replace(/^send/, "").replace(/Email$/, "").replace(/([a-z])([A-Z])/g, "$1 $2"), subject: defaultSubject, bodyHtml, kind: "system", status: "published", guidance: `Current automatic email from ${fn.name.text}. ${defaultSubject === "{{original_subject}}" ? "The subject token retains its existing case-specific wording." : ""}`, variables: [...expressions.values()].map(key => ({ key, label: key.replace(/_/g, " ") })), requiredVariables });
  const entries = [...expressions].map(([expression, key]) => `${JSON.stringify(key)}: String(${expression})`);
  entries.push('original_subject: String(typeof subject === "undefined" ? "" : subject)');
  // The actual subject is supplied from sendEmail's params, so no function-scope subject dependency.
  entries.pop();
  if (!alreadyRegistered) insertions.push({ position: object.getStart(file) + 1, text: ` templateCode: ${JSON.stringify(code)}, templateValues: { ${entries.join(", ")} },` });
}

if (catalog.length !== 43) throw new Error(`Expected 43 senders, found ${catalog.length}`);
fs.writeFileSync(outputPath, "// Generated by scripts/register-system-emails.cjs from email.service.ts.\nexport const systemEmailCatalog: Array<{code: string; name: string; subject: string; bodyHtml: string; kind: 'system'; status: 'published'; guidance: string; variables: Array<{key: string; label: string}>; requiredVariables: string[]}> = " + JSON.stringify(catalog, null, 2) + ";\n");
let updated = source;
for (const insertion of insertions.sort((a, b) => b.position - a.position)) updated = updated.slice(0, insertion.position) + insertion.text + updated.slice(insertion.position);
fs.writeFileSync(sourcePath, updated);
console.log(`Registered ${catalog.length} existing senders`);
